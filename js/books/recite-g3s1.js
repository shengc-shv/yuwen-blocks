/* 三上 · 按课文内容填空（背诵关题库，原创编写）
 *
 * 为什么单独一套：期末卷里「按课文内容填空」固定占 10-12 分，是孩子最容易白丢的分，
 * 而这套判定方式跟选择题完全不同——必须真的回忆起那个词并写出来，不能用排除法蒙。
 *
 * 版权处理（重要）：
 *   1. 古诗、文言文属公有领域，题干可直接引用原句；
 *   2. 现代文不整段复制教材原文，一律用「课文里说……」的自编提示句 + 填课文原词，
 *      既考到了背诵，又不复制段落。想答对必须回忆起课文，蒙不出来。
 *
 * 每个条目：
 *   it = [题干, 正确答案, [干扰1,干扰2,干扰3], [可接受写法], 输入框提示, 解析]
 * 选择题的干扰项不用一眼假的凑数项，而是同课里容易记混的词、背串的句子、形近写法。
 *
 * 错因口径：不给 trap，所以答错会归到「还没学会」而不是「看错了」——
 * 背诵题答错就是没背熟，不该混进粗心统计里。
 */
