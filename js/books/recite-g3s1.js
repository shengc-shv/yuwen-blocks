  var OUT = [];
  var TITLES = {};
  (window.YW_UNITS || []).forEach(function (u) {
    (u.lessons || []).forEach(function (l) { TITLES[l.n] = l.t; });
  });

  function add(lesson, unit, list) {
    list.forEach(function (it, i) {
      // 正确答案按题序轮转落位，避免整套题答案全在 A
      var pos = i % 4;
      var others = it[2].slice(0, 3);
      var opts = [];
      var oi = 0;
      for (var k = 0; k < 4; k++) opts.push(k === pos ? it[1] : others[oi++]);
      var trap = it[6] || [];
      OUT.push({
        id: 'rc-g3s1-' + lesson + '-' + (i + 1),
        book: 'g3s1', grade: 3, term: '上',
        unit: unit, lesson: lesson, lessonTitle: TITLES[lesson] || '',
        kp: 'beisong', dim: 'beisong',
        stem: it[0], options: opts, answer: pos, trap: trap,
        // 只有给了可接受写法（it[3]）的才是填空题；给 null 的是选择/辨析题，
        // 不能带 fill，否则会被渲染成「手打一整句话」的填空，孩子没法写。
        fill: it[3] ? { accepts: it[3], hint: it[4] || '把答案写完整' } : null,
        focus: [it[1]], tip: it[5], recite: true, rotated: true,
      });
    });
  }

